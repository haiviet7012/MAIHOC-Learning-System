#!/usr/bin/env node
import Database from "better-sqlite3";
import dotenv from "dotenv";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const filename = fileURLToPath(import.meta.url);
const dirname = path.dirname(filename);
dotenv.config({ path: path.join(dirname, ".env") });
dotenv.config({ path: path.resolve(dirname, "..", ".env") });
dotenv.config();

export function quoteIdent(value) {
  return '"' + String(value).replaceAll('"', '""') + '"';
}

export function postgresType(sqliteType) {
  const type = String(sqliteType || "").trim().toUpperCase();
  if (/\bBLOB\b/.test(type)) return "BYTEA";
  if (/\b(REAL|FLOA|DOUB)\b/.test(type)) return "DOUBLE PRECISION";
  if (/\b(NUMERIC|DECIMAL)\b/.test(type)) return "NUMERIC";
  if (/\b(INT|INTEGER|TINYINT|SMALLINT|BIGINT)\b/.test(type)) return "BIGINT";
  return "TEXT";
}

export function postgresDefault(value) {
  if (value == null || String(value).trim() === "") return null;
  let result = String(value).trim();
  while (result.startsWith("(") && result.endsWith(")")) {
    result = result.slice(1, -1).trim();
  }
  if (/^datetime\s*\(\s*'now'\s*\)$/i.test(result)) return "CURRENT_TIMESTAMP";
  if (/^current_timestamp$/i.test(result)) return "CURRENT_TIMESTAMP";
  if (/^null$/i.test(result)) return "NULL";
  if (/^[-+]?\d+(?:\.\d+)?$/.test(result)) return result;
  if (/^'.*'$/.test(result) || /^".*"$/.test(result)) return result;
  return null;
}

export function extractChecks(createSql) {
  const checks = [];
  const regex = /\bCHECK\s*\(((?:[^()]|\([^()]*\))*)\)/gi;
  let match;
  while ((match = regex.exec(String(createSql || ""))) !== null) {
    if (match[1].trim()) checks.push(match[1].trim());
  }
  return [...new Set(checks)];
}

function arg(name, fallback = null) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
}

function safeName(prefix, table, suffix) {
  const raw = (prefix + "_" + table + "_" + suffix).replace(/[^a-zA-Z0-9_]/g, "_");
  return raw.length <= 60 ? raw : raw.slice(0, 50) + "_" + Buffer.from(raw).toString("hex").slice(0, 8);
}

function sourceSchema(db) {
  const sourceTables = db.prepare(
    "SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
  ).all();

  return sourceTables.map((sourceTable) => {
    const columns = db.pragma("table_info(" + quoteIdent(sourceTable.name) + ")");
    const foreignKeys = db.pragma("foreign_key_list(" + quoteIdent(sourceTable.name) + ")");
    const indexes = db.pragma("index_list(" + quoteIdent(sourceTable.name) + ")").map((index) => ({
      ...index,
      columns: db.pragma("index_xinfo(" + quoteIdent(index.name) + ")")
        .filter((column) => Number(column.key) === 1)
        .sort((a, b) => Number(a.seqno) - Number(b.seqno))
    }));
    const count = db.prepare("SELECT COUNT(*) AS count FROM " + quoteIdent(sourceTable.name)).get().count;
    const integrity = db.prepare("PRAGMA integrity_check(" + quoteIdent(sourceTable.name) + ")").all();
    const fkProblems = db.prepare("PRAGMA foreign_key_check(" + quoteIdent(sourceTable.name) + ")").all();
    return {
      name: sourceTable.name,
      sql: sourceTable.sql || "",
      columns,
      foreignKeys,
      indexes,
      count: Number(count),
      integrity: integrity.map((row) => Object.values(row)[0]),
      fkProblems
    };
  });
}

export function buildCreateTableSql(table) {
  const primaryKey = table.columns
    .filter((column) => Number(column.pk) > 0)
    .sort((a, b) => Number(a.pk) - Number(b.pk));
  const singleIntegerId = primaryKey.length === 1
    && String(primaryKey[0].name).toLowerCase() === "id"
    && /\bINT(?:EGER)?\b/i.test(primaryKey[0].type || "");
  const definitions = table.columns.map((column) => {
    const parts = [quoteIdent(column.name), postgresType(column.type)];
    const identity = singleIntegerId && Number(column.pk) > 0;
    if (identity) parts.push("GENERATED BY DEFAULT AS IDENTITY");
    if (Number(column.notnull) && Number(column.pk) === 0) parts.push("NOT NULL");
    const defaultValue = postgresDefault(column.dflt_value);
    if (!identity && defaultValue !== null) parts.push("DEFAULT " + defaultValue);
    return parts.join(" ");
  });

  if (primaryKey.length) {
    const pkName = safeName("pk", table.name, primaryKey.map((column) => column.name).join("_"));
    definitions.push("CONSTRAINT " + quoteIdent(pkName) + " PRIMARY KEY (" +
      primaryKey.map((column) => quoteIdent(column.name)).join(", ") + ")");
  }
  return {
    sql: "CREATE TABLE " + quoteIdent(table.name) + " (" + definitions.join(", ") + ")",
    identityColumn: singleIntegerId ? primaryKey[0].name : null
  };
}

function indexColumns(index) {
  if (Number(index.partial)) {
    throw new Error('Partial index "' + index.name + '" on "' + index.table + '" is unsupported; inspect and migrate it explicitly.');
  }
  if (!index.columns.length || index.columns.some((column) => Number(column.cid) < 0 || !column.name)) {
    throw new Error('Expression index "' + index.name + '" cannot be converted safely.');
  }
  return index.columns.map((column) => {
    const ident = quoteIdent(column.name);
    const expression = String(column.coll || "").toUpperCase() === "NOCASE" && Number(index.unique)
      ? "LOWER(" + ident + ")"
      : ident;
    return expression + (Number(column.desc) ? " DESC" : " ASC");
  });
}

function foreignKeyGroups(table) {
  const groups = new Map();
  for (const fk of table.foreignKeys) {
    if (!groups.has(fk.id)) groups.set(fk.id, []);
    groups.get(fk.id).push(fk);
  }
  return [...groups.entries()].map(([id, rows]) => ({
    id,
    rows: rows.sort((a, b) => Number(a.seq) - Number(b.seq)),
    referencedTable: rows[0].table,
    onUpdate: String(rows[0].on_update || "NO ACTION").toUpperCase(),
    onDelete: String(rows[0].on_delete || "NO ACTION").toUpperCase()
  }));
}

async function main() {
  const mainPath = path.resolve(arg("--main-db", path.join(dirname, "data", "maihoc.sqlite")));
  const resultsPath = path.resolve(arg("--results-db", path.join(dirname, "data", "learning-results.sqlite")));
  const apply = process.argv.includes("--apply");
  const confirmTarget = arg("--confirm-target");
  if (!process.env.DATABASE_URL) {
    throw new Error("Thiếu DATABASE_URL. Cấu hình trong server/.env hoặc file .env ở thư mục dự án.");
  }
  for (const file of [mainPath, resultsPath]) {
    if (!fs.existsSync(file)) throw new Error("Không tìm thấy SQLite database: " + file);
  }
  if (mainPath === resultsPath) throw new Error("Hai đường dẫn SQLite không được trỏ tới cùng một file.");

  const mainDb = new Database(mainPath, { readonly: true, fileMustExist: true });
  const resultsDb = new Database(resultsPath, { readonly: true, fileMustExist: true });
  let pgPool;
  try {
    const checkIntegrity = (db, label) => {
      const issues = db.prepare("PRAGMA integrity_check").all().map((row) => Object.values(row)[0]).filter((value) => value !== "ok");
      if (issues.length) throw new Error(label + " integrity_check thất bại: " + issues.slice(0, 5).join("; "));
    };
    checkIntegrity(mainDb, "maihoc.sqlite");
    checkIntegrity(resultsDb, "learning-results.sqlite");

    const mainTables = sourceSchema(mainDb).map((table) => ({ ...table, source: "main" }));
    const resultTables = sourceSchema(resultsDb).map((table) => ({ ...table, source: "results" }));
    const tables = mainTables.concat(resultTables);
    const names = new Set();

    for (const table of tables) {
      if (names.has(table.name)) {
        throw new Error('Hai SQLite database có bảng trùng tên "' + table.name + '". Cần xử lý trùng tên trước khi import.');
      }
      names.add(table.name);
      if (table.integrity.some((value) => value !== "ok")) throw new Error('Bảng "' + table.name + '" có lỗi integrity.');
      if (table.fkProblems.length) throw new Error('Bảng "' + table.name + '" có lỗi foreign key nguồn: ' + JSON.stringify(table.fkProblems.slice(0, 3)));
      for (const index of table.indexes) index.table = table.name;
    }

    const users = mainDb.prepare("SELECT id, name, email, role FROM users ORDER BY id").all();
    if (users.length !== 1 || Number(users[0].id) !== 1 || users[0].role !== "admin") {
      throw new Error("Dừng import: yêu cầu nguồn chỉ có users.id=1 với role=admin. Thực tế: " + JSON.stringify(users));
    }
    const resultTable = resultTables.find((table) => table.name === "learning_results");
    if (resultTable) {
      const extraUsers = resultsDb.prepare("SELECT user_id, COUNT(*) AS count FROM learning_results WHERE user_id <> 1 GROUP BY user_id").all();
      if (extraUsers.length) throw new Error("learning_results còn dữ liệu user_id khác 1: " + JSON.stringify(extraUsers));
    }

    for (const table of tables) {
      for (const fk of table.foreignKeys) {
        if (!names.has(fk.table)) throw new Error('Bảng "' + table.name + '" tham chiếu tới bảng không tìm thấy: "' + fk.table + '".');
      }
    }

    const imported = await import("./postgres.js");
    pgPool = imported.pool;
    const client = await pgPool.connect();
    try {
      const result = await client.query("SELECT current_database() AS database_name, current_user AS database_user, now() AS server_time");
      const target = result.rows[0];
      const publicTables = await client.query(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE' ORDER BY table_name"
      );
      const report = {
        mode: apply ? "APPLY" : "DRY RUN",
        target,
        mainSQLite: mainPath,
        resultsSQLite: resultsPath,
        retainedUser: users[0],
        tableCount: tables.length,
        totalRows: tables.reduce((sum, table) => sum + table.count, 0),
        tables: tables.map((table) => ({ database: table.source, table: table.name, rows: table.count, columns: table.columns.length })),
        existingPublicTables: publicTables.rows.map((row) => row.table_name),
        warnings: [
          "This copies schema/data only; it does not switch server.js or other application modules to PostgreSQL.",
          "Existing PostgreSQL tables are never dropped or overwritten.",
          "The source is required to contain exactly admin ID 1."
        ]
      };
      console.log(JSON.stringify(report, null, 2));

      if (!apply) {
        console.log("DRY RUN: chưa có thay đổi nào trên PostgreSQL. Xác nhận báo cáo trước khi import.");
        return;
      }
      if (!confirmTarget || confirmTarget !== target.database_name) {
        throw new Error("Cần --confirm-target với đúng database_name đã in ở báo cáo: " + target.database_name);
      }
      if (publicTables.rows.length) {
        throw new Error("Schema public của PostgreSQL không trống. Dừng để tránh trộn/ghi đè dữ liệu.");
      }

      await client.query("BEGIN");
      try {
        const identities = [];
        const fks = [];
        const regularIndexes = [];
        const checks = [];

        for (const table of tables) {
          const built = buildCreateTableSql(table);
          await client.query(built.sql);
          if (built.identityColumn) identities.push({ table: table.name, column: built.identityColumn });

          for (const index of table.indexes) {
            if (String(index.origin) === "pk") continue;
            const columns = indexColumns(index);
            const indexName = safeName(Number(index.unique) ? "ux" : "ix", table.source + "_" + table.name, index.name);
            const indexSql = "CREATE " + (Number(index.unique) ? "UNIQUE " : "") + "INDEX " +
              quoteIdent(indexName) + " ON " + quoteIdent(table.name) + " (" + columns.join(", ") + ")";
            if (Number(index.unique)) await client.query(indexSql);
            else regularIndexes.push(indexSql);
          }

          extractChecks(table.sql).forEach((expression, index) => checks.push({
            table: table.name,
            name: safeName("ck", table.name, String(index + 1)),
            expression
          }));
          foreignKeyGroups(table).forEach((fk) => fks.push({ table: table.name, ...fk }));
        }

        for (const table of tables) {
          if (!table.count) continue;
          const sourceDb = table.source === "main" ? mainDb : resultsDb;
          const rows = sourceDb.prepare("SELECT * FROM " + quoteIdent(table.name)).all();
          const columns = table.columns.map((column) => column.name);
          const batchSize = Math.max(1, Math.min(100, Math.floor(60000 / Math.max(columns.length, 1))));
          for (let offset = 0; offset < rows.length; offset += batchSize) {
            const batch = rows.slice(offset, offset + batchSize);
            const values = [];
            const groups = batch.map((row) => {
              const slots = columns.map((column) => {
                values.push(row[column] === undefined ? null : row[column]);
                return "$" + values.length;
              });
              return "(" + slots.join(", ") + ")";
            });
            const query = "INSERT INTO " + quoteIdent(table.name) + " (" + columns.map(quoteIdent).join(", ") +
              ") VALUES " + groups.join(", ");
            await client.query(query, values);
          }
        }

        for (const check of checks) {
          await client.query("ALTER TABLE " + quoteIdent(check.table) + " ADD CONSTRAINT " +
            quoteIdent(check.name) + " CHECK (" + check.expression + ")");
        }
        for (const fk of fks) {
          const referenced = tables.find((table) => table.name === fk.referencedTable);
          const referencedPk = referenced.columns.filter((column) => Number(column.pk) > 0)
            .sort((a, b) => Number(a.pk) - Number(b.pk)).map((column) => column.name);
          const from = fk.rows.map((row) => row.from);
          const to = fk.rows.map((row, index) => row.to || referencedPk[index]);
          const allowed = new Set(["NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"]);
          if (!allowed.has(fk.onUpdate) || !allowed.has(fk.onDelete)) {
            throw new Error("Foreign key action không hỗ trợ ở " + fk.table + ": " + fk.onUpdate + "/" + fk.onDelete);
          }
          await client.query(
            "ALTER TABLE " + quoteIdent(fk.table) + " ADD CONSTRAINT " +
            quoteIdent(safeName("fk", fk.table, String(fk.id))) + " FOREIGN KEY (" + from.map(quoteIdent).join(", ") +
            ") REFERENCES " + quoteIdent(fk.referencedTable) + " (" + to.map(quoteIdent).join(", ") +
            ") ON UPDATE " + fk.onUpdate + " ON DELETE " + fk.onDelete
          );
        }
        for (const sql of regularIndexes) await client.query(sql);

        for (const identity of identities) {
          const relation = "public." + identity.table;
          const sequenceSql = "SELECT setval(pg_get_serial_sequence($1, $2), " +
            "GREATEST(COALESCE(MAX(" + quoteIdent(identity.column) + "), 1), 1), COUNT(*) > 0) FROM " +
            quoteIdent(identity.table);
          await client.query(sequenceSql, [relation, identity.column]);
        }

        for (const table of tables) {
          const targetCount = await client.query("SELECT COUNT(*)::bigint AS count FROM " + quoteIdent(table.name));
          if (Number(targetCount.rows[0].count) !== table.count) {
            throw new Error("Sai số lượng bản ghi ở " + table.name + ": SQLite=" + table.count +
              ", PostgreSQL=" + targetCount.rows[0].count);
          }
        }
        await client.query("COMMIT");
        console.log("IMPORT THÀNH CÔNG. Kiểm tra dữ liệu trước khi chuyển application traffic sang PostgreSQL.");
      } catch (error) {
        await client.query("ROLLBACK").catch(() => {});
        throw error;
      }
    } finally {
      client.release();
    }
  } finally {
    mainDb.close();
    resultsDb.close();
    if (pgPool) await pgPool.end().catch(() => {});
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === filename) {
  main().catch((error) => {
    console.error("LỖI MIGRATION:", error.message);
    process.exitCode = 1;
  });
}
