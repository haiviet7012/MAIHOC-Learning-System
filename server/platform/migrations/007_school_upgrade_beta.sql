-- Additive beta schema. Existing IDs, account plans and assessment history are preserved.
CREATE TABLE school_upgrade_access (
 school_id BIGINT PRIMARY KEY REFERENCES schools(id), enabled BOOLEAN NOT NULL DEFAULT true,
 expires_at TIMESTAMPTZ, daily_ai_calls INTEGER NOT NULL DEFAULT 100 CHECK(daily_ai_calls BETWEEN 1 AND 10000)
);
CREATE TABLE school_upgrade_usage (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 school_id BIGINT NOT NULL REFERENCES schools(id), day DATE NOT NULL DEFAULT ((now() AT TIME ZONE 'UTC')::date),
 calls INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(user_id,school_id,day)
);
CREATE TABLE school_document_jobs (
 id UUID PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id),
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN ('exam','answers','notebook','notebook_feedback')),
 title TEXT NOT NULL, subject TEXT NOT NULL, parent_id UUID REFERENCES school_document_jobs(id) ON DELETE CASCADE,
 source_key TEXT, source_type TEXT, payload JSONB NOT NULL DEFAULT '{}', result JSONB,
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','needs_review','ready','failed')),
 attempts INTEGER NOT NULL DEFAULT 0, lease_until TIMESTAMPTZ, lease_token UUID, error TEXT,
 revision INTEGER NOT NULL DEFAULT 0, request_key UUID NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,request_key)
);
CREATE INDEX school_document_queue_idx ON school_document_jobs(status,created_at);
CREATE TABLE school_room_sessions (
 id UUID PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id), class_id BIGINT,
 owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, title TEXT NOT NULL,
 closed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(school_id,class_id) REFERENCES classes(school_id,id)
);
CREATE TABLE school_room_members (
 room_id UUID NOT NULL REFERENCES school_room_sessions(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, consent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 lease_until TIMESTAMPTZ NOT NULL DEFAULT now()+interval '90 seconds', PRIMARY KEY(room_id,user_id)
);
CREATE TABLE school_room_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id UUID NOT NULL REFERENCES school_room_sessions(id) ON DELETE CASCADE,
 user_id BIGINT REFERENCES users(id) ON DELETE CASCADE, content TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE school_room_recordings (
 id UUID PRIMARY KEY, room_id UUID NOT NULL REFERENCES school_room_sessions(id) ON DELETE CASCADE,
 egress_id TEXT, object_key TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'starting', error TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), expires_at TIMESTAMPTZ NOT NULL DEFAULT now()+interval '30 days'
);
CREATE UNIQUE INDEX school_room_one_recording_idx ON school_room_recordings(room_id)
 WHERE status IN ('starting','recording','stopping','processing');
CREATE TABLE school_lab_sessions (
 id UUID PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id),
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, experiment TEXT NOT NULL,
 parameters JSONB NOT NULL, measurements JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE school_interventions (
 id UUID PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id), class_id BIGINT NOT NULL,
 teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, topic_id BIGINT NOT NULL,
 student_ids JSONB NOT NULL, question_ids JSONB NOT NULL, title TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','assigned')),
 assignment_ids JSONB NOT NULL DEFAULT '[]', created_at TIMESTAMPTZ NOT NULL DEFAULT now(), approved_at TIMESTAMPTZ,
 FOREIGN KEY(school_id,class_id) REFERENCES classes(school_id,id),
 FOREIGN KEY(school_id,topic_id) REFERENCES curriculum_nodes(school_id,id)
);
ALTER TABLE school_room_sessions ADD COLUMN presenter_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
CREATE TABLE school_room_ai_requests (
 id UUID PRIMARY KEY, room_id UUID NOT NULL REFERENCES school_room_sessions(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 result JSONB, status TEXT NOT NULL DEFAULT 'pending', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE school_document_jobs ADD COLUMN published_ids JSONB NOT NULL DEFAULT '[]';
ALTER TABLE school_room_sessions ADD COLUMN locked BOOLEAN NOT NULL DEFAULT false;

-- Preserve storage cleanup work across account/job/room cascade deletion.
CREATE TABLE school_asset_deletions (
 object_key TEXT PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE FUNCTION queue_school_source_deletion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.source_key IS NOT NULL THEN INSERT INTO school_asset_deletions(object_key) VALUES(OLD.source_key) ON CONFLICT DO NOTHING; END IF;
 RETURN OLD;
END;
$$;
CREATE TRIGGER school_document_delete_asset BEFORE DELETE ON school_document_jobs FOR EACH ROW EXECUTE FUNCTION queue_school_source_deletion();
CREATE FUNCTION queue_school_recording_deletion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO school_asset_deletions(object_key) VALUES(OLD.object_key) ON CONFLICT DO NOTHING;
 RETURN OLD;
END;
$$;
CREATE TRIGGER school_recording_delete_asset BEFORE DELETE ON school_room_recordings FOR EACH ROW EXECUTE FUNCTION queue_school_recording_deletion();
