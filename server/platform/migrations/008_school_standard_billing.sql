ALTER TABLE users ADD COLUMN IF NOT EXISTS school_expires_at TIMESTAMPTZ;
-- Retire Premium while preserving historical access as grandfathered Legacy.
UPDATE users SET school_plan='legacy' WHERE school_plan='premium';

CREATE TABLE billing_orders (
 id UUID PRIMARY KEY,
 order_code TEXT NOT NULL UNIQUE,
 buyer_user_id BIGINT NOT NULL REFERENCES users(id),
 buyer_type TEXT NOT NULL CHECK (buyer_type IN ('student','school')),
 school_id BIGINT REFERENCES schools(id),
 plan_code TEXT NOT NULL DEFAULT 'standard' CHECK (plan_code='standard'),
 unit_price_vnd BIGINT NOT NULL CHECK (unit_price_vnd>0),
 quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 200),
 amount_vnd BIGINT NOT NULL CHECK (amount_vnd>0),
 duration_days INTEGER NOT NULL CHECK (duration_days>0),
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','expired','cancelled')),
 payment_deadline TIMESTAMPTZ NOT NULL,
 paid_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX billing_orders_buyer_idx ON billing_orders(buyer_user_id,created_at DESC);
CREATE INDEX billing_orders_status_idx ON billing_orders(status,payment_deadline);

CREATE TABLE billing_order_recipients (
 order_id UUID NOT NULL REFERENCES billing_orders(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 subscription_id UUID,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(order_id,user_id)
);
CREATE INDEX billing_order_recipients_user_idx ON billing_order_recipients(user_id,created_at DESC);

CREATE TABLE billing_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 gateway_transaction_id TEXT NOT NULL UNIQUE,
 order_id UUID REFERENCES billing_orders(id),
 gateway TEXT,
 account_number TEXT,
 transfer_type TEXT NOT NULL,
 transfer_amount BIGINT NOT NULL CHECK (transfer_amount>=0),
 transfer_content TEXT NOT NULL DEFAULT '',
 reference_code TEXT,
 transaction_date TEXT,
 status TEXT NOT NULL CHECK (status IN ('matched','unmatched','amount_mismatch','late_payment','order_not_pending','ignored')),
 payload JSONB NOT NULL DEFAULT '{}',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX billing_transactions_order_idx ON billing_transactions(order_id,created_at DESC);
CREATE INDEX billing_transactions_status_idx ON billing_transactions(status,created_at DESC);

CREATE TABLE billing_subscriptions (
 id UUID PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 order_id UUID NOT NULL REFERENCES billing_orders(id),
 school_id BIGINT REFERENCES schools(id),
 plan_code TEXT NOT NULL DEFAULT 'standard' CHECK (plan_code='standard'),
 starts_at TIMESTAMPTZ NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','expired','cancelled')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(order_id,user_id),
 CHECK(expires_at>starts_at)
);
CREATE INDEX billing_subscriptions_user_idx ON billing_subscriptions(user_id,status,expires_at DESC);
CREATE INDEX billing_subscriptions_expiry_idx ON billing_subscriptions(status,expires_at);

ALTER TABLE billing_order_recipients
 ADD CONSTRAINT billing_order_recipients_subscription_id_fkey
 FOREIGN KEY(subscription_id) REFERENCES billing_subscriptions(id);

CREATE TABLE billing_reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscription_id UUID NOT NULL UNIQUE REFERENCES billing_subscriptions(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','sending','sent','cancelled','failed')),
 attempts INTEGER NOT NULL DEFAULT 0,
 next_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 claim_token UUID,
 sent_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX billing_reminders_queue_idx ON billing_reminders(status,next_at);
