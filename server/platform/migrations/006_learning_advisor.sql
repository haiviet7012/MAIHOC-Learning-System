-- Additive only. Progress history starts at deployment; old snapshots are not backdated.
CREATE TABLE learning_activity_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 item_type TEXT NOT NULL, item_id TEXT NOT NULL, subject TEXT NOT NULL,
 progress_percent INTEGER NOT NULL CHECK(progress_percent BETWEEN 0 AND 100),
 status TEXT NOT NULL, occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX learning_activity_user_date_idx ON learning_activity_events(user_id,occurred_at);
CREATE FUNCTION record_learning_activity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.item_type <> 'test' AND (TG_OP = 'INSERT' OR NEW.progress_percent IS DISTINCT FROM OLD.progress_percent OR NEW.status IS DISTINCT FROM OLD.status) THEN
  INSERT INTO learning_activity_events(user_id,item_type,item_id,subject,progress_percent,status)
  VALUES(NEW.user_id,NEW.item_type,NEW.item_id,NEW.subject,NEW.progress_percent,NEW.status);
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER learning_progress_event AFTER INSERT OR UPDATE ON user_progress
 FOR EACH ROW EXECUTE FUNCTION record_learning_activity();
CREATE TABLE learning_advisor_threads (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 scope TEXT NOT NULL CHECK(scope IN ('school','learning')),
 school_id BIGINT REFERENCES schools(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((scope='school' AND school_id IS NOT NULL) OR (scope='learning' AND school_id IS NULL))
);
CREATE INDEX learning_advisor_owner_idx ON learning_advisor_threads(user_id,scope,school_id);
CREATE TABLE learning_advisor_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 thread_id UUID NOT NULL REFERENCES learning_advisor_threads(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK(role IN ('user','model')), content TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE learning_advisor_roadmaps (
 id UUID PRIMARY KEY, thread_id UUID NOT NULL REFERENCES learning_advisor_threads(id) ON DELETE CASCADE,
 plan JSONB NOT NULL, applied_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE learning_advisor_calls (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX learning_advisor_calls_user_idx ON learning_advisor_calls(user_id,created_at);
