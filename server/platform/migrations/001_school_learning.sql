ALTER TABLE tests ADD COLUMN IF NOT EXISTS class_code TEXT;
CREATE TABLE schools (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','suspended')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE school_memberships (
 school_id BIGINT NOT NULL REFERENCES schools(id), user_id BIGINT NOT NULL REFERENCES users(id),
 role TEXT NOT NULL CHECK(role IN ('school_admin','teacher','student')), status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','archived')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(school_id,user_id)
);
CREATE INDEX memberships_user_idx ON school_memberships(user_id,status);
CREATE TABLE academic_years (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id),
 code TEXT NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL, CHECK(end_date>start_date),
 UNIQUE(school_id,code), UNIQUE(school_id,id)
);
CREATE TABLE terms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, academic_year_id BIGINT NOT NULL,
 name TEXT NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL CHECK(end_date>start_date),
 FOREIGN KEY(school_id,academic_year_id) REFERENCES academic_years(school_id,id), UNIQUE(school_id,id)
);
CREATE TABLE classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, academic_year_id BIGINT NOT NULL,
 class_code TEXT NOT NULL, name TEXT NOT NULL, grade_level INTEGER NOT NULL CHECK(grade_level BETWEEN 1 AND 12),
 status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','archived')),
 FOREIGN KEY(school_id,academic_year_id) REFERENCES academic_years(school_id,id),
 UNIQUE(school_id,academic_year_id,class_code), UNIQUE(school_id,id), UNIQUE(school_id,academic_year_id,id)
);
CREATE TABLE student_enrollments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, academic_year_id BIGINT NOT NULL,
 class_id BIGINT NOT NULL, student_id BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','ended')),
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(), ended_at TIMESTAMPTZ,
 reason TEXT NOT NULL, approved_by BIGINT NOT NULL REFERENCES users(id),
 FOREIGN KEY(school_id,academic_year_id,class_id) REFERENCES classes(school_id,academic_year_id,id),
 FOREIGN KEY(school_id,student_id) REFERENCES school_memberships(school_id,user_id)
);
CREATE UNIQUE INDEX enrollment_active_idx ON student_enrollments(school_id,academic_year_id,student_id) WHERE status='active';
CREATE INDEX enrollment_class_idx ON student_enrollments(school_id,class_id,status);
CREATE TABLE course_offerings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, class_id BIGINT NOT NULL,
 subject TEXT NOT NULL, term_id BIGINT, FOREIGN KEY(school_id,class_id) REFERENCES classes(school_id,id),
 FOREIGN KEY(school_id,term_id) REFERENCES terms(school_id,id), UNIQUE(school_id,id)
);
CREATE TABLE teacher_course_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, class_id BIGINT NOT NULL,
 teacher_id BIGINT NOT NULL, subject TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('homeroom','subject')),
 FOREIGN KEY(school_id,class_id) REFERENCES classes(school_id,id), FOREIGN KEY(school_id,teacher_id) REFERENCES school_memberships(school_id,user_id),
 UNIQUE(school_id,class_id,teacher_id,subject,kind)
);
CREATE UNIQUE INDEX teacher_homeroom_idx ON teacher_course_assignments(school_id,class_id) WHERE kind='homeroom';
CREATE INDEX teacher_scope_idx ON teacher_course_assignments(school_id,teacher_id,class_id);
CREATE TABLE curriculum_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id),
 name TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(school_id,name), UNIQUE(school_id,id)
);
CREATE TABLE curriculum_nodes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, curriculum_version_id BIGINT NOT NULL,
 subject TEXT NOT NULL, grade INTEGER NOT NULL CHECK(grade BETWEEN 1 AND 12), name TEXT NOT NULL,
 FOREIGN KEY(school_id,curriculum_version_id) REFERENCES curriculum_versions(school_id,id), UNIQUE(school_id,id)
);
CREATE TABLE question_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id),
 created_by BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(school_id,id)
);
CREATE TABLE question_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, question_item_id BIGINT NOT NULL,
 version INTEGER NOT NULL CHECK(version>0), subject TEXT NOT NULL, grade INTEGER NOT NULL CHECK(grade BETWEEN 1 AND 12),
 curriculum_node_id BIGINT NOT NULL, type TEXT NOT NULL CHECK(type IN ('multiple_choice','short_answer','essay')),
 stem TEXT NOT NULL, choices JSONB NOT NULL DEFAULT '[]', answer TEXT NOT NULL, source TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved','archived')),
 reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMPTZ,
 FOREIGN KEY(school_id,question_item_id) REFERENCES question_items(school_id,id),
 FOREIGN KEY(school_id,curriculum_node_id) REFERENCES curriculum_nodes(school_id,id),
 UNIQUE(question_item_id,version), UNIQUE(school_id,id)
);
CREATE INDEX question_scope_idx ON question_versions(school_id,status,subject,grade);
CREATE TABLE assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id), title TEXT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 subject TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'published' CHECK(status IN ('published','archived')), UNIQUE(school_id,id)
);
CREATE TABLE assessment_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, assessment_id BIGINT NOT NULL,
 question_version_id BIGINT NOT NULL, position INTEGER NOT NULL, points NUMERIC NOT NULL DEFAULT 1 CHECK(points>0), snapshot JSONB NOT NULL,
 FOREIGN KEY(school_id,assessment_id) REFERENCES assessments(school_id,id),
 FOREIGN KEY(school_id,question_version_id) REFERENCES question_versions(school_id,id), UNIQUE(assessment_id,position), UNIQUE(assessment_id,id)
);
CREATE TABLE assessment_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, assessment_id BIGINT NOT NULL, class_id BIGINT NOT NULL,
 open_at TIMESTAMPTZ NOT NULL, close_at TIMESTAMPTZ NOT NULL CHECK(close_at>open_at),
 duration_minutes INTEGER NOT NULL CHECK(duration_minutes BETWEEN 1 AND 240),
 FOREIGN KEY(school_id,assessment_id) REFERENCES assessments(school_id,id), FOREIGN KEY(school_id,class_id) REFERENCES classes(school_id,id),
 UNIQUE(school_id,id), UNIQUE(school_id,id,assessment_id)
);
CREATE TABLE assessment_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL, assignment_id BIGINT NOT NULL, assessment_id BIGINT NOT NULL,
 student_id BIGINT NOT NULL REFERENCES users(id), started_at TIMESTAMPTZ NOT NULL DEFAULT now(), deadline_at TIMESTAMPTZ NOT NULL,
 submitted_at TIMESTAMPTZ, status TEXT NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','submitted','pending_grade','graded')),
 version INTEGER NOT NULL DEFAULT 0, answers JSONB NOT NULL DEFAULT '{}', idempotency_key TEXT,
 FOREIGN KEY(school_id,assignment_id,assessment_id) REFERENCES assessment_assignments(school_id,id,assessment_id),
 UNIQUE(assignment_id,student_id), UNIQUE(assessment_id,id), UNIQUE(school_id,id)
);
CREATE INDEX attempts_student_idx ON assessment_attempts(student_id,status);
CREATE TABLE attempt_answers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assessment_id BIGINT NOT NULL, attempt_id BIGINT NOT NULL,
 assessment_item_id BIGINT NOT NULL, answer TEXT NOT NULL, correct BOOLEAN, points NUMERIC,
 FOREIGN KEY(assessment_id,attempt_id) REFERENCES assessment_attempts(assessment_id,id),
 FOREIGN KEY(assessment_id,assessment_item_id) REFERENCES assessment_items(assessment_id,id), UNIQUE(attempt_id,assessment_item_id)
);
CREATE TABLE assessment_results (
 attempt_id BIGINT PRIMARY KEY REFERENCES assessment_attempts(id), score NUMERIC, scale NUMERIC NOT NULL DEFAULT 10,
 feedback TEXT, grading_version INTEGER NOT NULL DEFAULT 1, graded_by BIGINT REFERENCES users(id), graded_at TIMESTAMPTZ
);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT REFERENCES schools(id), actor_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id TEXT NOT NULL, detail JSONB NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_school_idx ON audit_logs(school_id,created_at DESC);
CREATE TABLE platform_settings (name TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE legacy_class_mappings (
 class_code TEXT PRIMARY KEY, school_id BIGINT NOT NULL, academic_year_id BIGINT NOT NULL, class_id BIGINT NOT NULL,
 FOREIGN KEY(school_id,academic_year_id,class_id) REFERENCES classes(school_id,academic_year_id,id)
);
CREATE TABLE legacy_test_sessions (
 id UUID PRIMARY KEY, test_id TEXT NOT NULL REFERENCES tests(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id),
 started_at TIMESTAMPTZ NOT NULL, deadline_at TIMESTAMPTZ NOT NULL, answers JSONB NOT NULL DEFAULT '{}', version INTEGER NOT NULL DEFAULT 0,
 submission_id BIGINT REFERENCES test_submissions(id), UNIQUE(test_id,user_id)
);
CREATE TABLE platform_jobs (
 id UUID PRIMARY KEY, school_id BIGINT REFERENCES schools(id), user_id BIGINT NOT NULL REFERENCES users(id),
 kind TEXT NOT NULL CHECK(kind IN ('ai_tutor')), payload JSONB NOT NULL,
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','completed','failed')),
 attempts INTEGER NOT NULL DEFAULT 0, available_at TIMESTAMPTZ NOT NULL DEFAULT now(), lease_until TIMESTAMPTZ,
 lease_token UUID, result JSONB, error TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), completed_at TIMESTAMPTZ
);
CREATE INDEX jobs_claim_idx ON platform_jobs(status,available_at);
