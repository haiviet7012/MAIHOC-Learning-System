/**
 * Returns deterministic conversation ID for 1-1 chat between two users.
 */
export function getDirectConversationId(userId1, userId2) {
  const id1 = Number(userId1);
  const id2 = Number(userId2);
  const min = Math.min(id1, id2);
  const max = Math.max(id1, id2);
  return `direct_${min}_${max}`;
}

/**
 * Ensures a direct conversation between userA and userB exists in DB.
 */
export async function getOrCreateDirectConversation(userAId, userBId) {
  const sender = await db.prepare('SELECT * FROM users WHERE id=?').get(userAId);
  const recipient = await db.prepare('SELECT * FROM users WHERE id=?').get(userBId);
  if (!canAccessSchool(sender) || !canAccessSchool(recipient)) throw new Error('Chat riêng chỉ dành cho tài khoản School.');
  if (Number(userAId) === Number(userBId)) {
    throw new Error("Không thể nhắn tin riêng với chính mình.");
  }

  const targetUser = await db.prepare("SELECT id, name FROM users WHERE id = ?").get(userBId);
  if (!targetUser) {
    throw new Error("Người dùng không tồn tại.");
  }

  const convId = getDirectConversationId(userAId, userBId);

  const createTx = db.transaction(async () => {
    const existing = await db.prepare("SELECT id FROM chat_conversations WHERE id = ?").get(convId);
    if (!existing) {
      await db
        .prepare(`
          INSERT INTO chat_conversations (id, type, title, created_at, updated_at)
          VALUES (?, 'direct', '', datetime('now'), datetime('now'))
        `)
        .run(convId);
    }
    const addPart = db.prepare(`
      INSERT OR IGNORE INTO chat_participants (conversation_id, user_id, joined_at, last_read_message_id)
      VALUES (?, ?, datetime('now'), 0)
    `);
    await addPart.run(convId, userAId);
    await addPart.run(convId, userBId);
  });
  await createTx();

  return { id: convId, type: "direct", partner: { id: Number(targetUser.id), name: targetUser.name } };
}

/**
 * Checks if a user is permitted to view/participate in conversation.
 */
export async function isParticipant(conversationId, userId) {
  if (conversationId === "global") {
    await db
      .prepare(`
        INSERT OR IGNORE INTO chat_participants (conversation_id, user_id, joined_at, last_read_message_id)
        VALUES ('global', ?, datetime('now'), 0)
      `)
      .run(userId);
    return true;
  }
  const user = await db.prepare('SELECT * FROM users WHERE id=?').get(userId);
  if (!canAccessSchool(user)) return false;
  const row = await db
    .prepare(`
      SELECT 1 FROM chat_participants WHERE conversation_id = ? AND user_id = ?
    `)
    .get(conversationId, userId);
  return Boolean(row);
}

