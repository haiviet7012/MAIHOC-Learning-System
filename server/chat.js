// Setup Socket.IO & Chat REST API
// ----------------------------------------------------
export function setupChat(server, app) {
  const io = chatIO = new SocketIOServer(server, {
    path: "/socket.io",
    cors: {
      origin: true,
      credentials: true
    },
    pingTimeout: 30000,
    pingInterval: 25000
  });

  const retentionTimer = setInterval(() => {
    purgeExpiredChatMessages().catch(error => console.error('Chat retention cleanup failed:', error.message));
  }, 60000);
  retentionTimer.unref();
  server.once('close', () => clearInterval(retentionTimer));
  let attachmentSchemaReady;
  app.use('/api/chat', async (_req, res, next) => {
    try {
      await (attachmentSchemaReady ||= ensureChatAttachmentSchema().catch(error => { attachmentSchemaReady = null; throw error; }));
      await purgeExpiredChatMessages(); next();
    }
    catch { res.status(503).json({ error: 'Không thể tải lịch sử chat lúc này.' }); }
  });

  const chatUpload = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: 10 * 1024 * 1024, files: 1 }
  });

  app.post('/api/chat/attachments', (req, res, next) => {
    chatUpload.single('attachment')(req, res, error => {
      if (!error) return next();
      const message = error instanceof multer.MulterError && error.code === 'LIMIT_FILE_SIZE'
        ? 'Tệp đính kèm tối đa 10 MB.'
        : 'Không thể đọc tệp đính kèm.';
      res.status(400).json({ error: message });
    });
  }, async (req, res) => {
    if (!req.user) return res.status(401).json({ error: 'Vui lòng đăng nhập.' });
    const conversationId = String(req.body?.conversationId || '').trim();
    const content = String(req.body?.content || '').trim();
    const file = req.file;
    if (!conversationId || !file) return res.status(400).json({ error: 'Thiếu cuộc trò chuyện hoặc tệp đính kèm.' });
    if (!file.size) return res.status(400).json({ error: 'Tệp đính kèm đang trống.' });
    if (content.length > 2000) return res.status(400).json({ error: 'Tin nhắn không được vượt quá 2.000 ký tự.' });
    if (!(await isParticipant(conversationId, req.user.id))) return res.status(403).json({ error: 'Bạn không có quyền gửi tệp trong cuộc trò chuyện này.' });
    if (!checkRateLimit(req.user.id)) return res.status(429).json({ error: 'Bạn đang gửi tin nhắn quá nhanh. Vui lòng thử lại sau.' });

    const attachmentName = String(file.originalname || 'tep-dinh-kem').replace(/[\u0000-\u001f\u007f]/g, '').slice(0, 255) || 'tep-dinh-kem';
    const attachmentType = String(file.mimetype || 'application/octet-stream').slice(0, 120);
    const attachmentKey = `chat/${new Date().toISOString().slice(0, 10)}/${crypto.randomUUID()}`;
    let uploaded = false;
    let storedInDatabase = false;
    try {
      try {
        await uploadToR2({ key: attachmentKey, body: file.buffer, contentType: attachmentType });
        uploaded = true;
      } catch (storageError) {
        // Keep chat attachments usable when the optional object storage is unavailable.
        console.warn('Chat attachment R2 upload failed; using database fallback:', storageError.message);
      }
      let insertedMessage;
      const sendTx = db.transaction(async () => {
        const insert = await db.prepare(`
          INSERT INTO chat_messages (conversation_id,sender_id,content,attachment_key,attachment_name,attachment_type,attachment_size,attachment_data,created_at)
          VALUES (?,?,?,?,?,?,?,?,datetime('now'))
        `).run(conversationId, req.user.id, content, uploaded ? attachmentKey : null, attachmentName, attachmentType, file.size, uploaded ? null : file.buffer);
        storedInDatabase = !uploaded;
        await db.prepare(`UPDATE chat_conversations SET updated_at=datetime('now') WHERE id=?`).run(conversationId);
        await db.prepare(`UPDATE chat_participants SET last_read_message_id=? WHERE conversation_id=? AND user_id=?`).run(insert.lastInsertRowid, conversationId, req.user.id);
        insertedMessage = await db.prepare(`
          SELECT m.id,m.conversation_id,m.sender_id,m.content,m.attachment_name,m.attachment_type,m.attachment_size,m.created_at,u.name AS sender_name
          FROM chat_messages m JOIN users u ON u.id=m.sender_id WHERE m.id=?
        `).get(insert.lastInsertRowid);
      });
      await sendTx();
      const message = {
        id: Number(insertedMessage.id), conversationId: insertedMessage.conversation_id,
        senderId: Number(insertedMessage.sender_id), senderName: insertedMessage.sender_name,
        content: insertedMessage.content, createdAt: insertedMessage.created_at,
        attachment: { name: insertedMessage.attachment_name, type: insertedMessage.attachment_type, size: Number(insertedMessage.attachment_size || 0) }
      };
      io.to(`conv_${conversationId}`).emit('chat:new-message', message);
      if (conversationId === 'global') io.emit('chat:global-activity', { lastMessage: message });
      else {
        const participants = await db.prepare(`SELECT user_id FROM chat_participants WHERE conversation_id=?`).all(conversationId);
        for (const participant of participants) io.to(`user_${participant.user_id}`).emit('chat:conversation-updated', { conversationId, lastMessage: message });
      }
      res.json({ ok: true, message });
    } catch (error) {
      if (uploaded) await deleteFromR2(attachmentKey).catch(() => {});
      console.error('Chat attachment error:', error);
      res.status(500).json({
        error: storedInDatabase ? 'Không lưu được tin nhắn đính kèm. Vui lòng thử lại.' : 'Không thể lưu tệp đính kèm. Vui lòng thử lại.',
        code: storedInDatabase ? 'CHAT_MESSAGE_SAVE_FAILED' : 'CHAT_ATTACHMENT_STORAGE_FAILED'
      });
    }
  });

  app.get('/api/chat/messages/:id/attachment', async (req, res) => {
    if (!req.user) return res.status(401).json({ error: 'Vui lòng đăng nhập.' });
    const message = await db.prepare(`
      SELECT conversation_id,attachment_key,attachment_name,attachment_type,attachment_data FROM chat_messages WHERE id=?
    `).get(Number(req.params.id));
    if (!message?.attachment_key && !message?.attachment_data) return res.status(404).json({ error: 'Không tìm thấy tệp đính kèm.' });
    if (!(await isParticipant(message.conversation_id, req.user.id))) return res.status(403).json({ error: 'Không có quyền xem tệp này.' });
    try {
      const bytes = message.attachment_data
        ? Buffer.from(message.attachment_data)
        : Buffer.from(await (await readFromR2(message.attachment_key)).Body.transformToByteArray());
      const type = /^[\w.+-]+\/[\w.+-]+$/.test(message.attachment_type || '') ? message.attachment_type : 'application/octet-stream';
      const inline = type.startsWith('image/');
      res.set('Content-Type', type);
      res.set('Cache-Control', 'private, max-age=300');
      res.set('Content-Disposition', `${inline ? 'inline' : 'attachment'}; filename*=UTF-8''${encodeURIComponent(message.attachment_name || 'tep-dinh-kem')}`);
      res.send(bytes);
    } catch {
      res.status(404).json({ error: 'Tệp đính kèm không còn tồn tại.' });
    }
  });

  // Track online users: userId (number) => Set of socketId (string)
  const onlineUsers = new Map();

  function isUserOnline(userId) {
    const sockets = onlineUsers.get(Number(userId));
    return Boolean(sockets && sockets.size > 0);
  }

  // Socket Authentication Middleware using maihoc.sid cookie
  io.use(async (socket, next) => {
    try {
      const cookieHeader = socket.request.headers.cookie || "";
      const cookies = parseCookies(cookieHeader);
      const token = cookies[SESSION_COOKIE];

      if (!token || !/^[a-f0-9]{64}$/i.test(token)) {
        return next(new Error("Vui lòng đăng nhập để kết nối chat."));
      }

      const session = await db
        .prepare(`
          SELECT u.id, u.name, u.email, u.role, u.admin_level, s.expires_at
          FROM sessions s JOIN users u ON u.id = s.user_id
          WHERE s.token_hash = ?
        `)
        .get(hashToken(token));

      if (!session || Number(session.expires_at) <= Date.now()) {
        return next(new Error("Phiên đăng nhập đã hết hạn."));
      }

      socket.user = {
        id: Number(session.id),
        name: session.name,
        email: session.email,
        role: session.role
      };
      next();
    } catch (err) {
      next(new Error("Lỗi xác thực kết nối."));
    }
  });

  // Rate limit tracking for chat messages: userId => Array of timestamps
  const messageTimestamps = new Map();
  function checkRateLimit(userId) {
    const now = Date.now();
    let timestamps = messageTimestamps.get(userId) || [];
    timestamps = timestamps.filter((t) => now - t < 5000);
    if (timestamps.length >= 6) {
      return false;
    }
    timestamps.push(now);
    messageTimestamps.set(userId, timestamps);
    return true;
  }

  io.on("connection", (socket) => {
    const user = socket.user;
    const userId = Number(user.id);

    if (!onlineUsers.has(userId)) {
      onlineUsers.set(userId, new Set());
    }
    const userSockets = onlineUsers.get(userId);
    const wasOffline = userSockets.size === 0;
    userSockets.add(socket.id);

    socket.join(`user_${userId}`);
    socket.join("conv_global");
    isParticipant("global", userId).catch(() => {});

    if (wasOffline) {
      io.emit("chat:presence", { userId, isOnline: true });
    }

    socket.on("chat:check-presence", (targetUserId, callback) => {
      const online = isUserOnline(targetUserId);
      if (typeof callback === "function") callback({ userId: targetUserId, isOnline: online });
    });

    socket.on("chat:join", async (conversationId, callback) => {
      try {
        const convId = String(conversationId || "").trim();
        if (!convId) return;

        if (!(await isParticipant(convId, userId))) {
          if (typeof callback === "function") {
            callback({ error: "Bạn không có quyền tham gia cuộc trò chuyện này." });
          }
          return;
        }

        socket.join(`conv_${convId}`);
        if (typeof callback === "function") callback({ ok: true, conversationId: convId });
      } catch (err) {
        if (typeof callback === "function") callback({ error: "Không thể tham gia phòng chat." });
      }
    });

    socket.on("chat:leave", (conversationId) => {
      const convId = String(conversationId || "").trim();
      if (convId && convId !== "global") {
        socket.leave(`conv_${convId}`);
      }
    });

    socket.on("chat:send", async (data, callback) => {
      try {
        if (!data || typeof data !== "object") {
          if (typeof callback === "function") callback({ error: "Dữ liệu không hợp lệ." });
          return;
        }

        const conversationId = String(data.conversationId || "").trim();
        const content = String(data.content || "").trim();
        const clientTempId = data.clientTempId ? String(data.clientTempId) : null;

        if (!conversationId) {
          if (typeof callback === "function") callback({ error: "Thiếu mã cuộc trò chuyện." });
          return;
        }

        if (!content) {
          if (typeof callback === "function") callback({ error: "Nội dung tin nhắn không được để trống." });
          return;
        }

        if (content.length > 2000) {
          if (typeof callback === "function") callback({ error: "Tin nhắn không được vượt quá 2.000 ký tự." });
          return;
        }

        if (!checkRateLimit(userId)) {
          if (typeof callback === "function") {
            callback({ error: "Bạn đang gửi tin nhắn quá nhanh. Vui lòng thử lại sau vài giây." });
          }
          return;
        }

        if (!(await isParticipant(conversationId, userId))) {
          if (typeof callback === "function") {
            callback({ error: "Bạn không có quyền gửi tin nhắn trong cuộc trò chuyện này." });
          }
          return;
        }

        let insertedMessage = null;
        let convInfo = null;

        const sendTx = db.transaction(async () => {
          await purgeExpiredChatMessages();

          const insertStmt = db.prepare(`
            INSERT INTO chat_messages (conversation_id, sender_id, content, created_at)
            VALUES (?, ?, ?, datetime('now'))
          `);
          const res = await insertStmt.run(conversationId, userId, content);

          await db
            .prepare(`
              UPDATE chat_conversations SET updated_at = datetime('now') WHERE id = ?
            `)
            .run(conversationId);

          await db
            .prepare(`
              UPDATE chat_participants
              SET last_read_message_id = ?
              WHERE conversation_id = ? AND user_id = ?
            `)
            .run(res.lastInsertRowid, conversationId, userId);

          insertedMessage = await db
            .prepare(`
              SELECT m.id, m.conversation_id, m.sender_id, m.content, m.created_at, u.name AS sender_name
              FROM chat_messages m
              JOIN users u ON u.id = m.sender_id
              WHERE m.id = ?
            `)
            .get(res.lastInsertRowid);

          convInfo = await db
            .prepare(`
              SELECT id, type, title FROM chat_conversations WHERE id = ?
            `)
            .get(conversationId);
        });
        await sendTx();

        const messagePayload = {
          id: Number(insertedMessage.id),
          conversationId: insertedMessage.conversation_id,
          senderId: Number(insertedMessage.sender_id),
          senderName: insertedMessage.sender_name,
          content: insertedMessage.content,
          createdAt: insertedMessage.created_at,
          clientTempId
        };

        io.to(`conv_${conversationId}`).emit("chat:new-message", messagePayload);

        if (convInfo && convInfo.type === "direct") {
          const participants = await db
            .prepare(`
              SELECT user_id FROM chat_participants WHERE conversation_id = ?
            `)
            .all(conversationId);

          for (const p of participants) {
            io.to(`user_${p.user_id}`).emit("chat:conversation-updated", {
              conversationId,
              lastMessage: messagePayload
            });
          }
        } else if (conversationId === "global") {
          io.emit("chat:global-activity", {
            lastMessage: messagePayload
          });
        }

        if (typeof callback === "function") {
          callback({ ok: true, message: messagePayload });
        }
      } catch (err) {
        console.error("Chat send error:", err);
        if (typeof callback === "function") callback({ error: "Lỗi hệ thống khi gửi tin nhắn." });
      }
    });

    socket.on("chat:read", async (data) => {
      try {
        const conversationId = String(data?.conversationId || "").trim();
        const messageId = Number(data?.messageId || 0);
        if (!conversationId || !messageId) return;

        if (!(await isParticipant(conversationId, userId))) return;

        await db
          .prepare(`
            UPDATE chat_participants
            SET last_read_message_id = GREATEST(last_read_message_id, ?)
            WHERE conversation_id = ? AND user_id = ?
          `)
          .run(messageId, conversationId, userId);

        socket.to(`conv_${conversationId}`).emit("chat:read-receipt", {
          conversationId,
          userId,
          messageId
        });
      } catch (err) {
        console.error("Chat read error:", err);
      }
    });

    socket.on("chat:typing", (data) => {
      const conversationId = String(data?.conversationId || "").trim();
      const isTyping = Boolean(data?.isTyping);
      if (!conversationId) return;

      socket.to(`conv_${conversationId}`).emit("chat:user-typing", {
        conversationId,
        userId,
        userName: user.name,
        isTyping
      });
    });

    socket.on("disconnect", () => {
      if (onlineUsers.has(userId)) {
        const sockets = onlineUsers.get(userId);
        sockets.delete(socket.id);
        if (sockets.size === 0) {
          onlineUsers.delete(userId);
          io.emit("chat:presence", { userId, isOnline: false });
        }
      }
    });
  });

  // ----------------------------------------------------
  // REST API Endpoints
  // ----------------------------------------------------

  // 1. Get conversations list for current user
  app.get("/api/chat/conversations", async (req, res) => {
    if (!req.user) return res.status(401).json({ error: "Vui lòng đăng nhập." });
    const currentUserId = req.user.id;

    try {
      await isParticipant("global", currentUserId);

      const rows = await db
        .prepare(`
          SELECT c.id, c.type, c.title, c.updated_at, p.last_read_message_id
          FROM chat_participants p
          JOIN chat_conversations c ON c.id = p.conversation_id
          WHERE p.user_id = ?
          ORDER BY c.updated_at DESC
        `)
        .all(currentUserId);

      const conversations = await Promise.all(
        rows.map(async (conv) => {
          const lastMsg = await db
            .prepare(`
              SELECT m.id,m.content,m.sender_id,m.attachment_name,m.attachment_type,m.attachment_size,m.created_at,u.name AS sender_name
              FROM chat_messages m
              JOIN users u ON u.id = m.sender_id
              WHERE m.conversation_id = ?
                AND (? != 'global' OR m.created_at > datetime('now', '-24 hours'))
              ORDER BY m.id DESC LIMIT 1
            `)
            .get(conv.id, conv.id);

          const unreadRow = await db
            .prepare(`
              SELECT COUNT(id) AS unread
              FROM chat_messages
              WHERE conversation_id = ? AND id > ? AND sender_id != ?
                AND (? != 'global' OR created_at > datetime('now', '-24 hours'))
            `)
            .get(conv.id, conv.last_read_message_id || 0, currentUserId, conv.id);

          let partner = null;
          if (conv.type === "direct") {
            const partnerRow = await db
              .prepare(`
                SELECT u.id, u.name
                FROM chat_participants cp
                JOIN users u ON u.id = cp.user_id
                WHERE cp.conversation_id = ? AND cp.user_id != ?
              `)
              .get(conv.id, currentUserId);

            if (partnerRow) {
              partner = {
                id: Number(partnerRow.id),
                name: partnerRow.name,
                isOnline: isUserOnline(partnerRow.id)
              };
            }
          }

          return {
            id: conv.id,
            type: conv.type,
            title: conv.type === "global" ? "Phòng học tập chung" : partner ? partner.name : "Tin nhắn",
            partner,
            updatedAt: conv.updated_at,
            unreadCount: unreadRow ? Number(unreadRow.unread) : 0,
            lastMessage: lastMsg
              ? {
                  id: Number(lastMsg.id),
                  content: lastMsg.content,
                  attachment: lastMsg.attachment_name ? { name: lastMsg.attachment_name, type: lastMsg.attachment_type, size: Number(lastMsg.attachment_size || 0) } : null,
                  senderId: Number(lastMsg.sender_id),
                  senderName: lastMsg.sender_name,
                  createdAt: lastMsg.created_at
                }
              : null
          };
        })
      );

      res.json({ conversations: conversations.filter(c => c.type !== "direct" || (canAccessSchool(req.user) && c.partner)) });
    } catch (err) {
      console.error("GET /api/chat/conversations error:", err);
      res.status(500).json({ error: "Không thể lấy danh sách cuộc trò chuyện." });
    }
  });

  // 2. Search users for direct chat
  app.get("/api/chat/users", async (req, res) => {
    if (!canAccessSchool(req.user)) return res.status(req.user ? 403 : 401).json({error:'Chat riêng chỉ dành cho School.'});
    if (!req.user) return res.status(401).json({ error: "Vui lòng đăng nhập." });
    const currentUserId = req.user.id;
    const query = String(req.query.q || req.query.search || "").trim();

    try {
      let users = [];
      if (query) {
        users = await db
          .prepare(`
            SELECT id, name
            FROM users
            WHERE id != ?
              AND (name LIKE ? COLLATE NOCASE OR email LIKE ? COLLATE NOCASE)
            ORDER BY name COLLATE NOCASE ASC LIMIT 25
          `)
          .all(currentUserId, `%${query}%`, `%${query}%`);
      } else {
        users = await db
          .prepare(`
            SELECT id, name
            FROM users
            WHERE id != ?
            ORDER BY id DESC LIMIT 20
          `)
          .all(currentUserId);
      }

      const eligible = [];
      for (const u of users) if (canAccessSchool(await db.prepare('SELECT * FROM users WHERE id=?').get(u.id))) eligible.push(u);
      const results = eligible.map((u) => ({
        id: Number(u.id),
        name: u.name,
        isOnline: isUserOnline(u.id)
      }));

      res.json({ users: results });
    } catch (err) {
      console.error("GET /api/chat/users error:", err);
      res.status(500).json({ error: "Không thể tìm kiếm người dùng." });
    }
  });

  // 3. Create or get 1-1 conversation with a user
  app.post("/api/chat/direct", async (req, res) => {
    if (!req.user) return res.status(401).json({ error: "Vui lòng đăng nhập." });
    const currentUserId = req.user.id;
    const targetUserId = Number(req.body.targetUserId);

    if (!targetUserId || isNaN(targetUserId)) {
      return res.status(400).json({ error: "Mã người nhận không hợp lệ." });
    }

    try {
      const conv = await getOrCreateDirectConversation(currentUserId, targetUserId);
      conv.partner.isOnline = isUserOnline(conv.partner.id);
      res.json(conv);
    } catch (err) {
      res.status(400).json({ error: err.message || "Không thể tạo cuộc trò chuyện." });
    }
  });

  // 4. Get message history for a conversation with pagination
  app.get("/api/chat/conversations/:id/messages", async (req, res) => {
    if (!req.user) return res.status(401).json({ error: "Vui lòng đăng nhập." });
    const currentUserId = req.user.id;
    const convId = String(req.params.id || "").trim();
    const beforeId = Number(req.query.before || 0);
    const limit = Math.min(Math.max(Number(req.query.limit || 40), 10), 100);

    if (!convId) return res.status(400).json({ error: "Mã cuộc trò chuyện không hợp lệ." });

    try {
      if (!(await isParticipant(convId, currentUserId))) {
        return res.status(403).json({ error: "Bạn không có quyền xem cuộc trò chuyện này." });
      }

      let messages = [];
      if (beforeId > 0) {
        messages = await db
          .prepare(`
            SELECT m.id,m.conversation_id,m.sender_id,m.content,m.attachment_name,m.attachment_type,m.attachment_size,m.created_at,u.name AS sender_name
            FROM chat_messages m
            JOIN users u ON u.id = m.sender_id
            WHERE m.conversation_id = ? AND m.id < ?
              AND (? != 'global' OR m.created_at > datetime('now', '-24 hours'))
            ORDER BY m.id DESC LIMIT ?
          `)
          .all(convId, beforeId, convId, limit);
      } else {
        messages = await db
          .prepare(`
            SELECT m.id,m.conversation_id,m.sender_id,m.content,m.attachment_name,m.attachment_type,m.attachment_size,m.created_at,u.name AS sender_name
            FROM chat_messages m
            JOIN users u ON u.id = m.sender_id
            WHERE m.conversation_id = ?
              AND (? != 'global' OR m.created_at > datetime('now', '-24 hours'))
            ORDER BY m.id DESC LIMIT ?
          `)
          .all(convId, convId, limit);
      }

      messages.reverse();

      res.json({
        conversationId: convId,
        messages: messages.map((m) => ({
          id: Number(m.id),
          conversationId: m.conversation_id,
          senderId: Number(m.sender_id),
          senderName: m.sender_name,
          content: m.content,
          attachment: m.attachment_name ? { name: m.attachment_name, type: m.attachment_type, size: Number(m.attachment_size || 0) } : null,
          createdAt: m.created_at
        }))
      });
    } catch (err) {
      console.error("GET messages error:", err);
      res.status(500).json({ error: "Không thể lấy lịch sử tin nhắn." });
    }
  });

  // 5. Mark conversation as read via HTTP
  app.post("/api/chat/conversations/:id/read", async (req, res) => {
    if (!req.user) return res.status(401).json({ error: "Vui lòng đăng nhập." });
    const currentUserId = req.user.id;
    const convId = String(req.params.id || "").trim();
    const messageId = Number(req.body.messageId || 0);

    if (!convId) return res.status(400).json({ error: "Mã cuộc trò chuyện không hợp lệ." });

    try {
      if (!(await isParticipant(convId, currentUserId))) {
        return res.status(403).json({ error: "Không có quyền truy cập." });
      }

      if (messageId > 0) {
        await db
          .prepare(`
            UPDATE chat_participants
            SET last_read_message_id = GREATEST(last_read_message_id, ?)
            WHERE conversation_id = ? AND user_id = ?
          `)
          .run(messageId, convId, currentUserId);
      } else {
        const maxRow = await db
          .prepare(`
            SELECT MAX(id) AS max_id FROM chat_messages WHERE conversation_id = ?
          `)
          .get(convId);
        if (maxRow && maxRow.max_id) {
          await db
            .prepare(`
              UPDATE chat_participants
              SET last_read_message_id = ?
              WHERE conversation_id = ? AND user_id = ?
            `)
            .run(maxRow.max_id, convId, currentUserId);
        }
      }

      res.json({ ok: true });
    } catch (err) {
      res.status(500).json({ error: "Không thể cập nhật trạng thái đã đọc." });
    }
  });

  return io;
}
