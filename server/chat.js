export async function ensureChatAttachmentSchema(database = db) {
  await database.exec(`
    ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS attachment_key TEXT;
    ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS attachment_name TEXT;
    ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS attachment_type TEXT;
    ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS attachment_size BIGINT;
    ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS attachment_data BYTEA;
  `);
}

export async function initChatDatabase() {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS chat_conversations (
      id TEXT PRIMARY KEY,
      type TEXT NOT NULL CHECK(type IN ('global', 'direct')),
      title TEXT,
      created_at TEXT NOT NULL DEFAULT (datetime('now')),
      updated_at TEXT NOT NULL DEFAULT (datetime('now'))
    );

    CREATE TABLE IF NOT EXISTS chat_participants (
      conversation_id TEXT NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      joined_at TEXT NOT NULL DEFAULT (datetime('now')),
      last_read_message_id BIGINT NOT NULL DEFAULT 0,
      PRIMARY KEY (conversation_id, user_id)
    );

    CREATE TABLE IF NOT EXISTS chat_messages (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      conversation_id TEXT NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
      sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      content TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT (datetime('now'))
    );

    CREATE INDEX IF NOT EXISTS idx_chat_messages_conv ON chat_messages(conversation_id, id DESC);
    CREATE INDEX IF NOT EXISTS idx_chat_participants_user ON chat_participants(user_id, conversation_id);
    CREATE INDEX IF NOT EXISTS idx_chat_conversations_updated ON chat_conversations(updated_at DESC);
  `);

  await ensureChatAttachmentSchema();
  await purgeExpiredChatMessages();

  // Remove direct threads whose other account was already deleted.
  await db.query(`DELETE FROM chat_conversations c WHERE c.type='direct' AND
    (SELECT count(*) FROM chat_participants p JOIN users u ON u.id=p.user_id WHERE p.conversation_id=c.id)<2`);
  await db.query(`CREATE OR REPLACE FUNCTION remove_deleted_user_chat() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      DELETE FROM chat_conversations WHERE type='direct' AND id IN
        (SELECT conversation_id FROM chat_participants WHERE user_id=OLD.id);
      RETURN OLD;
    END; $$`);
  await db.query(`DROP TRIGGER IF EXISTS users_remove_chat ON users`);
  await db.query(`CREATE TRIGGER users_remove_chat BEFORE DELETE ON users FOR EACH ROW EXECUTE FUNCTION remove_deleted_user_chat()`);
  // Ensure default Global Chat room exists
  await db
    .prepare(`
      INSERT OR IGNORE INTO chat_conversations (id, type, title, created_at, updated_at)
      VALUES ('global', 'global', 'Phòng học tập chung', datetime('now'), datetime('now'))
    `)
    .run();


}

