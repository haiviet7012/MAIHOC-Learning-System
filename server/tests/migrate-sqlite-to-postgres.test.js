import test from "node:test";
import assert from "node:assert/strict";
import { extractChecks, postgresDefault, postgresType, quoteIdent, buildCreateTableSql } from "../migrate-sqlite-to-postgres.js";

test("quotes PostgreSQL identifiers safely", () => {
  assert.equal(quoteIdent('a"b'), '"a""b"');
});

test("maps common SQLite types", () => {
  assert.equal(postgresType("INTEGER"), "BIGINT");
  assert.equal(postgresType("REAL"), "DOUBLE PRECISION");
  assert.equal(postgresType("BLOB"), "BYTEA");
  assert.equal(postgresType("TEXT"), "TEXT");
});

test("translates common SQLite defaults conservatively", () => {
  assert.equal(postgresDefault("(datetime('now'))"), "CURRENT_TIMESTAMP");
  assert.equal(postgresDefault("'pending'"), "'pending'");
  assert.equal(postgresDefault("10"), "10");
  assert.equal(postgresDefault("custom_function()"), null);
});

test("extracts CHECK constraints with IN and BETWEEN", () => {
  assert.deepEqual(
    extractChecks("CREATE TABLE x (role TEXT CHECK(role IN ('user','admin')), score INTEGER CHECK(score BETWEEN 0 AND 100))"),
    ["role IN ('user','admin')", "score BETWEEN 0 AND 100"]
  );
});

test("creates identity for id primary key and preserves composite primary key", () => {
  const generated = buildCreateTableSql({
    name: "users",
    columns: [
      { name: "id", type: "INTEGER", notnull: 0, dflt_value: null, pk: 1 },
      { name: "email", type: "TEXT", notnull: 1, dflt_value: null, pk: 0 }
    ]
  });
  assert.match(generated.sql, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.equal(generated.identityColumn, "id");

  const composite = buildCreateTableSql({
    name: "chat_participants",
    columns: [
      { name: "conversation_id", type: "TEXT", notnull: 1, dflt_value: null, pk: 1 },
      { name: "user_id", type: "INTEGER", notnull: 1, dflt_value: null, pk: 2 }
    ]
  });
  assert.doesNotMatch(composite.sql, /IDENTITY/);
  assert.match(composite.sql, /PRIMARY KEY \("conversation_id", "user_id"\)/);
});
