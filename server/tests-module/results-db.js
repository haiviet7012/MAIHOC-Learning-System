const UPSERT_SUBJECT_SQL = `
  INSERT INTO subjects_catalog(code, name, default_scale, display_order, active, metadata_json, updated_at)
  VALUES(?, ?, ?, ?, 1, ?, datetime('now'))
  ON CONFLICT(code) DO UPDATE SET
    name = excluded.name,
    default_scale = COALESCE(excluded.default_scale, subjects_catalog.default_scale),
    updated_at = datetime('now')
`;

export async function initResultsDatabase(targetDb = resultsDb) {
  await targetDb.exec(`
    CREATE TABLE IF NOT EXISTS subjects_catalog (
      code TEXT PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      default_scale DOUBLE PRECISION NOT NULL DEFAULT 10,
      display_order BIGINT NOT NULL DEFAULT 100,
      active BIGINT NOT NULL DEFAULT 1,
      metadata_json TEXT NOT NULL DEFAULT '{}',
      created_at TEXT NOT NULL DEFAULT (datetime('now')),
      updated_at TEXT NOT NULL DEFAULT (datetime('now'))
    );

    CREATE TABLE IF NOT EXISTS learning_results (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      record_key TEXT NOT NULL UNIQUE,
      user_id BIGINT NOT NULL,
      user_name TEXT NOT NULL,
      user_email TEXT NOT NULL,
      subject_code TEXT NOT NULL,
      subject_name TEXT NOT NULL,
      grade TEXT NOT NULL DEFAULT '10',
      category TEXT NOT NULL,
      item_id TEXT NOT NULL,
      item_title TEXT NOT NULL,
      attempt_id BIGINT,
      completion_status TEXT NOT NULL DEFAULT 'completed',
      grading_status TEXT NOT NULL DEFAULT 'not_applicable',
      progress_percent BIGINT NOT NULL DEFAULT 100,
      score DOUBLE PRECISION,
      scale DOUBLE PRECISION DEFAULT 10,
      percent_score DOUBLE PRECISION,
      correct_count BIGINT,
      question_count BIGINT,
      duration_minutes BIGINT,
      time_spent_seconds BIGINT,
      fullscreen_exit_auto_submit BIGINT NOT NULL DEFAULT 0,
      open_at TEXT,
      close_at TEXT,
      started_at TEXT,
      submitted_at TEXT,
      graded_at TEXT,
      graded_by_id BIGINT,
      graded_by_name TEXT,
      section_breakdown_json TEXT,
      extra_metadata_json TEXT,
      updated_at TEXT NOT NULL DEFAULT (datetime('now'))
    );

    CREATE INDEX IF NOT EXISTS learning_results_user_idx ON learning_results(user_id, category, updated_at DESC);
    CREATE INDEX IF NOT EXISTS learning_results_subject_idx ON learning_results(subject_code, grade, category, submitted_at DESC);
    CREATE INDEX IF NOT EXISTS learning_results_item_idx ON learning_results(item_id, category, grading_status);
  `);

  const upsertSubjectStmt = targetDb.prepare(UPSERT_SUBJECT_SQL);
  for (const item of DEFAULT_SUBJECTS) {
    await upsertSubjectStmt.run(
      normalizeSubjectCode(item.name),
      item.name,
      item.scale,
      item.order,
      JSON.stringify({ extensible: true, version: 1 })
    );
  }
}

export async function ensureSubjectRegistered(subjectName, defaultScale = 10, metadata = {}) {
  const name = String(subjectName || "Toán").trim() || "Toán";
  const code = normalizeSubjectCode(name);
  await resultsDb
    .prepare(UPSERT_SUBJECT_SQL)
    .run(code, name, Number(defaultScale) || 10, 99, JSON.stringify(metadata || {}));
  return { code, name };
}

export async function listRegisteredSubjects() {
  const rows = await resultsDb
    .prepare(
      "SELECT code, name, default_scale AS defaultScale, display_order AS displayOrder, active, metadata_json AS metadataJson FROM subjects_catalog WHERE active=1 ORDER BY display_order ASC, name ASC"
    )
    .all();
  return rows.map((row) => {
    let metadata = {};
    try {
      metadata = JSON.parse(row.metadataJson || "{}");
    } catch {}
    return {
      code: row.code,
      name: row.name,
      defaultScale: Number(row.defaultScale) || 10,
      displayOrder: Number(row.displayOrder) || 99,
      metadata
    };
  });
}

