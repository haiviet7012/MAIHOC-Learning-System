import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { dismissDevelopmentNotice } from './browser-notices.mjs';

const origin = 'http://127.0.0.1:4198', password = randomUUID();
const preview = spawn(process.execPath, ['scripts/dev-preview.mjs'], {
  env: { ...process.env, PREVIEW_PORT: '4198', MAIHOC_PREVIEW_PASSWORD: password, MAIHOC_PREVIEW_PLATFORM_ENABLED: '0' },
  stdio: ['ignore', 'pipe', 'pipe'],
});
let browser;
try {
  await new Promise((resolve, reject) => {
    let out = '';
    const timer = setTimeout(() => reject(new Error('Preview timeout')), 60000);
    preview.stdout.on('data', chunk => { out += chunk; if (out.includes('isolated preview ready')) { clearTimeout(timer); resolve(); } });
    preview.stderr.on('data', chunk => process.stderr.write(chunk));
    preview.once('exit', code => { clearTimeout(timer); reject(new Error(`Preview exited ${code}`)); });
  });
  browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined) });
  await mkdir('test-results', { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  await context.addInitScript(() => localStorage.setItem('maihoc-theme', 'dark'));
  const login = await context.request.post(origin + '/api/auth/login', { headers: { Origin: origin }, data: { email: 'teacher@maihoc.test', password } });
  assert.ok(login.ok(), await login.text());
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/cdn\.jsdelivr.*mathjax/, route => route.abort());
  await page.goto(origin + '/school/question-bank');
  await dismissDevelopmentNotice(page);
  const wait = async () => { await page.locator('[data-qb-kpi="total"]').filter({ hasText: '8' }).waitFor(); };
  await wait();
  const resultCount = () => page.locator('[data-qb-results] > .qb-card').count();
  const click = action => page.locator(`[data-qb-action="${action}"]`).first().click();
  const dialog = page.locator('[data-qb-dialog]');
  assert.equal(await resultCount(), 6);
  assert.ok(await page.locator('[data-qb-results] math').count() > 0, 'Formulas render without the external MathJax CDN');
  assert.equal(await page.locator('.qb-card').first().evaluate(el => getComputedStyle(el).borderRadius), '16px');
  assert.equal(await page.getByText('Không gian đang được nâng cấp', { exact: true }).count(), 0);
  assert.equal((await context.request.get(origin + '/api/platform/context').then(r => r.json())).enabled, false);
  await page.screenshot({ path: 'test-results/question-bank-desktop-dark.png', fullPage: true });
  console.log('School shell and question bank work while the platform feature flag is disabled.');

  await page.locator('[name="search"]').fill('nguyen ham');
  assert.equal(await resultCount(), 1);
  await page.locator('[data-qb-filters] [name="level"]').selectOption('vd');
  assert.equal(await resultCount(), 0);
  await click('reset');
  await page.locator('[data-qb-filters] [name="subject"]').selectOption('Vật lý');
  assert.equal(await resultCount(), 2);
  await page.locator('[data-qb-filters] [name="type"]').selectOption('short_answer');
  assert.equal(await resultCount(), 1);
  await click('reset');
  assert.equal(await page.locator('[data-qb-tab="pro"]').count(), 0);
  assert.equal(await page.locator('[data-qb-account]').count(), 0);
  await page.locator('[data-qb-tab="pending"]').click(); assert.equal(await resultCount(), 8);
  await click('approve');
  await page.waitForFunction(() => document.querySelector('[data-qb-results]')?.children.length === 7);
  await page.locator('[data-qb-tab="personal"]').click(); assert.equal(await resultCount(), 2);
  console.log('Intersecting filters, remaining repositories and review approval pass.');

  await click('add');
  await dialog.locator('[name="topic"]').fill('Hàm số');
  await dialog.locator('[name="stem"]').fill('Tính giá trị $f(2)$ với $f(x)=2x+1$.');
  await dialog.locator('[name="type"]').selectOption('true_false');
  assert.equal(await dialog.locator('[name^="truth"]').count(), 4);
  await dialog.locator('[name="type"]').selectOption('essay');
  await dialog.locator('[name="answer"]').fill('Đúng công thức: 0,5 điểm. Đáp số: 0,5 điểm.');
  await dialog.locator('[name="type"]').selectOption('short_answer');
  await dialog.locator('[name="answer"]').fill('5');
  await dialog.locator('[name="solution"]').fill('$f(2)=2×2+1=5$.');
  assert.match(await dialog.locator('[data-qb-preview]').innerText(), /5/);
  await dialog.getByRole('button', { name: 'Lưu câu hỏi', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await resultCount(), 3);
  await page.reload(); await dismissDevelopmentNotice(page);
  await page.locator('[data-qb-tab="personal"]').click();
  await page.waitForFunction(() => document.querySelectorAll('[data-qb-results] > .qb-card').length === 3);
  assert.ok(await page.getByText('Tính giá trị', { exact: false }).count());
  console.log('Dynamic editor, live preview, saving and reload persistence pass.');

  await page.locator('[data-qb-tab="school"]').click();
  const source = page.locator('[data-qb-card="MATH12-089"]');
  await source.locator('[data-qb-action="clone"]').click();
  await source.locator('.qb-variant-card').first().waitFor();
  assert.equal(await source.locator('.qb-variant-card').count(), 2);
  await source.locator('[data-qb-action="save-variant"]').first().click();
  await page.waitForFunction(() => document.querySelector('[data-qb-kpi="ai"]').textContent === '1');
  await page.locator('[data-qb-action="dismiss-variant"]').first().click();
  assert.equal(await page.locator('.qb-variant-card').count(), 0);
  await page.locator('[data-qb-select="MATH12-089"]').check();
  await page.locator('[data-qb-select="MATH12-124"]').check();
  assert.match(await page.locator('[data-qb-basket]').innerText(), /Đã chọn: 2/);
  await click('shuffle'); await dialog.locator('[data-qb-exam-code]').waitFor();
  assert.equal(await dialog.locator('[data-qb-exam-code] option').count(), 2);
  await click('close'); await click('clear');
  await page.locator('[data-qb-select="MATH12-089"]').check();
  await page.locator('[data-qb-select="PHYS12-042"]').check();
  await click('export');
  assert.match(await page.locator('[data-qb-status]').innerText(), /cùng môn/);
  await click('clear');
  console.log('AI variant review, exam basket, shuffling and mixed-subject validation pass.');

  await click('matrix');
  await dialog.locator('[name="nb"]').fill('99');
  await dialog.getByRole('button', { name: 'Rút trích câu hỏi & Tạo đề ngay' }).click();
  assert.match(await dialog.locator('[data-qb-form-error]').innerText(), /hiện có/);
  await dialog.locator('[name="nb"]').fill('1');
  await dialog.locator('[name="th"]').fill('1');
  await dialog.locator('[name="vdc"]').fill('1');
  await dialog.locator('[name="codes"]').fill('3');
  await dialog.getByRole('button', { name: 'Rút trích câu hỏi & Tạo đề ngay' }).click();
  await dialog.locator('[data-qb-exam-code]').waitFor();
  assert.equal(await dialog.locator('[data-qb-exam-code] option').count(), 3);
  assert.equal(await dialog.locator('.qb-exam-question').count(), 3);
  await dialog.locator('[data-qb-exam-code]').selectOption('103');
  const download = page.waitForEvent('download'); await click('download');
  assert.equal((await download).suggestedFilename(), 'maihoc-de-kiem-tra.json');
  await page.screenshot({ path: 'test-results/question-bank-matrix-exam.png', fullPage: true });
  await click('send'); await page.locator('.qb-test-draft').waitFor();
  assert.match(await page.locator('.qb-test-draft').innerText(), /3 câu · 3 mã đề/);
  await page.locator('.qb-test-draft [data-route="question-bank"]').click();
  await page.locator('[data-qb-action="last-exam"]').waitFor();
  console.log('Matrix inventory errors, three generated exam codes, JSON download and Tests handoff pass.');

  assert.equal(await page.locator('[data-qb-account]').count(), 0);
  assert.equal(await page.locator('[data-qb-tab="pro"]').count(), 0);
  await page.locator('[data-qb-tab="school"]').click();
  await page.locator('#theme-toggle').click();
  assert.ok(await page.locator('html').evaluate(el => !el.classList.contains('dark')));
  await page.screenshot({ path: 'test-results/question-bank-desktop-light.png', fullPage: true });
  console.log('Removed demo account switch/Pro tab and theme switching pass.');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#theme-toggle').click();
  const overflow = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth }));
  assert.ok(overflow.scroll <= overflow.width + 1, JSON.stringify(overflow));
  await page.screenshot({ path: 'test-results/question-bank-mobile-dark.png', fullPage: true });
  await page.locator('[data-qb-select="MATH12-089"]').check();
  await page.screenshot({ path: 'test-results/question-bank-mobile-basket.png', fullPage: true });
  await click('matrix');
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'test-results/question-bank-mobile-matrix.png' });
  await click('close'); await click('clear');
  await click('import'); await click('import-sample');
  assert.match(await page.locator('[data-qb-status]').innerText(), /Đã nhập 1 câu hỏi mẫu/);
  assert.ok(await page.locator('[data-qb-tab="personal"]').getAttribute('aria-selected') === 'true');
  assert.deepEqual(errors, []);
  console.log('Mobile layout, floating basket, matrix dialog, import sample and zero browser errors pass.');
} finally {
  await browser?.close();
  preview.kill();
}
