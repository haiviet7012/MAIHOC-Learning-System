import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir, readFile } from 'node:fs/promises';
import ExcelJS from 'exceljs';
import { createTimetableWorkbook, parseTimetableWorkbook } from '../js/platform/timetable-xlsx.js';
const password = randomUUID();
const origin = 'http://127.0.0.1:4174';
const preview = spawn(process.execPath, ['scripts/dev-preview.mjs'], {
  env: { ...process.env, PREVIEW_PORT: '4174', MAIHOC_PREVIEW_PASSWORD: password, MAIHOC_PREVIEW_PLATFORM_ENABLED: '0' },
  stdio: ['ignore', 'pipe', 'pipe'],
});
let browser;
try {
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Preview startup timeout')), 60000);
    let output = '';
    preview.stdout.on('data', chunk => { output += chunk; if (output.includes('isolated preview ready')) { clearTimeout(timeout); resolve(); } });
    preview.stderr.on('data', chunk => process.stderr.write(chunk));
    preview.on('exit', code => { clearTimeout(timeout); reject(new Error(`Preview exited ${code}`)); });
  });
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/fonts\.googleapis|fonts\.gstatic|cdn\.jsdelivr/, route => route.abort());
  assert.equal((await context.request.get(origin + '/api/learning/timetable')).status(), 401);
  await page.goto(origin + '/learning');
  await page.locator('#login-open').click();
  await page.locator('#login-form [name=email]').fill('student@maihoc.test');
  await page.locator('#login-form [name=password]').fill(password);
  await page.locator('#login-form button[type=submit]').click();
  await page.getByRole('button', { name: 'Thiết lập thời khóa biểu của bạn', exact: true }).waitFor();
  assert.equal((await (await context.request.get(origin + '/api/platform/context')).json()).enabled, false);
  await page.getByRole('button', { name: 'Thiết lập thời khóa biểu của bạn', exact: true }).click();
  await page.locator('[data-place="0-0"]').waitFor();
  assert.equal(await page.locator('[data-place]').count(), 63);
  await page.locator('[data-subject-choice="Toán"]').dragTo(page.locator('[data-place="0-0"]'));
  await page.locator('[data-place="0-0"]').filter({ hasText: 'Toán' }).waitFor();
  await page.locator('[data-subject-choice="Toán"]').dragTo(page.locator('[data-place="8-6"]'));
  await page.locator('[data-place="8-6"]').click({ button: 'right' });
  assert.equal((await page.locator('[data-place="8-6"]').textContent()).trim(), '+');
  await page.locator('[data-place="8-6"]').click();
  await page.locator('[data-place="8-6"]').press('Delete');
  assert.equal((await page.locator('[data-place="8-6"]').textContent()).trim(), '+');
  await page.getByRole('button', { name: 'Lưu thời khóa biểu', exact: true }).click();
  await page.locator('[data-timetable-status]').filter({ hasText: 'Đã lưu thời khóa biểu vào tài khoản.' }).waitFor();
  const saved = (await (await context.request.get(origin + '/api/learning/timetable')).json()).timetable;
  assert.equal(saved.cells['0-0'], 'Toán');
  const put = body => context.request.put(origin + '/api/learning/timetable', { data: { ...body, layoutVersion: 2 }, headers: { Origin: origin } });
  assert.equal((await put({ cells: { '9-0': 'Toán' }, version: saved.version })).status(), 400);
  assert.equal((await put({ cells: { '0-0': '<script>' }, version: saved.version })).status(), 400);
  assert.equal((await put({ cells: {}, version: 0 })).status(), 409);
  assert.equal((await context.request.put(origin + '/api/learning/timetable', { data: { cells: {}, version: saved.version }, headers: { Origin: 'https://untrusted.example' } })).status(), 403);
  await page.reload();
  await page.locator('[data-place="0-0"]').filter({ hasText: 'Toán' }).waitFor();
  await page.getByRole('button', { name: 'Quay lại tổng quan', exact: true }).click();
  await page.getByRole('button', { name: 'Sửa thời khóa biểu hiện tại', exact: true }).waitFor();
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Tạo thời khóa biểu mới', exact: true }).click();
  await page.locator('[data-place="0-0"]').filter({ hasText: 'Toán' }).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Tạo thời khóa biểu mới', exact: true }).click();
  assert.ok(!(await page.locator('[data-place="0-0"]').textContent()).includes('Toán'));
  assert.equal((await (await context.request.get(origin + '/api/learning/timetable')).json()).timetable.cells['0-0'], 'Toán', 'Reset does not delete persisted schedule before save');
  await page.locator('[data-subject-choice="Tiếng Anh"]').click();
  await page.locator('[data-place="1-1"]').focus();
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Lưu thời khóa biểu', exact: true }).click();
  await page.locator('[data-timetable-status]').filter({ hasText: 'Đã lưu thời khóa biểu vào tài khoản.' }).waitFor();
  // School navigation, download, invalid upload, cancellation, then import/save/reopen.
  assert.equal(await page.locator('[data-sidebar-space="school"]').first().isVisible(), true);
  assert.equal(await page.locator('nav[data-sidebar-space="school"] [data-route="timetable"]').getAttribute('aria-current'), 'page');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('[data-export-timetable]').click();
  const download = await downloadEvent;
  assert.match(download.suggestedFilename(), /^MAIHOC-thoi-khoa-bieu-\d{4}-\d{2}-\d{2}\.xlsx$/);
  const exported = new ExcelJS.Workbook(); await exported.xlsx.load(await readFile(await download.path()));
  assert.deepEqual(parseTimetableWorkbook(exported).cells, { '1-1': 'Tiếng Anh' });
  const upload = async workbook => page.locator('[data-timetable-file]').setInputFiles({ name: 'lich.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(await workbook.xlsx.writeBuffer()) });
  const invalid = createTimetableWorkbook(ExcelJS, {}); invalid.getWorksheet('Thời khóa biểu').getCell('C6').value = 'Môn lạ';
  await upload(invalid);
  await page.locator('[data-timetable-status]').filter({ hasText: 'chưa được hỗ trợ' }).waitFor();
  assert.equal((await page.locator('[data-place="1-1"]').textContent()).trim(), 'Tiếng Anh');
  const importedCells = { '4-0': 'Hóa học', '8-6': 'IELTS' };
  page.once('dialog', dialog => dialog.dismiss());
  await upload(createTimetableWorkbook(ExcelJS, importedCells));
  await page.locator('[data-timetable-status]').filter({ hasText: 'Đã hủy nhập' }).waitFor();
  assert.equal((await page.locator('[data-place="1-1"]').textContent()).trim(), 'Tiếng Anh');
  page.once('dialog', dialog => dialog.accept());
  await upload(createTimetableWorkbook(ExcelJS, importedCells));
  await page.locator('[data-timetable-status]').filter({ hasText: 'Đã nhập 2 tiết học' }).waitFor();
  assert.equal((await page.locator('[data-place="8-6"]').textContent()).trim(), 'IELTS');
  assert.equal((await (await context.request.get(origin + '/api/learning/timetable')).json()).timetable.cells['1-1'], 'Tiếng Anh', 'Import does not persist until Save');
  await page.locator('[data-save-timetable]').click();
  await page.locator('[data-timetable-status]').filter({ hasText: 'Đã lưu thời khóa biểu vào tài khoản.' }).waitFor();
  await page.reload();
  await page.locator('[data-place="8-6"]').filter({ hasText: 'IELTS' }).waitFor();
  assert.deepEqual((await (await context.request.get(origin + '/api/learning/timetable')).json()).timetable.cells, importedCells);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No mobile page overflow');
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/timetable-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.screenshot({ path: 'test-results/timetable-desktop.png', fullPage: true });
  await context.request.put(origin + '/api/progress', { headers: { Origin: origin }, data: { itemType: 'document', itemId: 'learning-fixture', itemTitle: 'Tự học Toán', subject: 'Toán', grade: '12', status: 'in_progress', progressPercent: 40 } });
  for (const [itemId, progressPercent] of [['progress-zero', 0], ['progress-full', 100]]) await context.request.put(origin + '/api/progress', { headers: { Origin: origin }, data: { itemType: 'document', itemId, itemTitle: itemId, subject: 'Toán', grade: '12', status: 'in_progress', progressPercent } });
  await page.goto(origin + '/learning/progress');
  await page.getByRole('heading', { name: 'Tiến trình học tập', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Tự học Toán', exact: true }).waitFor();
  await page.locator('.learning-progress-list progress').first().waitFor();
  const tracks = await page.locator('.learning-progress-list progress').evaluateAll(nodes => nodes.map(n => ({ x: n.getBoundingClientRect().x, width: n.getBoundingClientRect().width })));
  assert.equal(tracks.length, 3);
  assert.ok(tracks.every(t => Math.abs(t.width - tracks[0].width) < 1 && Math.abs(t.x - tracks[0].x) < 1), '0%, 40% and 100% tracks align at both ends');
  assert.ok(await page.locator('.learning-progress-scroll').evaluate(n => {
    const edge = n.getBoundingClientRect().left + n.clientLeft + n.clientWidth;
    return [...n.querySelectorAll('progress')].every(p => p.getBoundingClientRect().right <= edge - 23);
  }), 'Progress tracks reserve 24px before the scrollbar gutter');
  await page.locator('.advisor-pull').click();
  await page.locator('.advisor-drawer .advisor-workspace').waitFor();
  await page.locator('.advisor-dismiss').click();
  assert.equal(await page.locator('.advisor-drawer').evaluate(n => n.inert), true);
  assert.ok(!(await page.locator('#view').textContent()).includes('School mới chưa được bật'));
  assert.ok((await page.locator('body').evaluate(el => getComputedStyle(el).fontFamily)).includes('Montserrat'));
  const teacher = await browser.newContext();
  await teacher.request.post(origin + '/api/auth/login', { data: { email: 'teacher@maihoc.test', password }, headers: { Origin: origin } });
  assert.equal((await (await teacher.request.get(origin + '/api/learning/timetable')).json()).timetable, null, 'Timetable is private per account');
  assert.equal((await (await context.request.get(origin + '/api/learning/timetable')).json()).timetable.cells['8-6'], 'IELTS');
  assert.deepEqual(errors, []);
  console.log('Learning checks passed: disabled School, personal progress, drag/drop, keyboard/mobile, save/reopen, reset confirmation, ownership, CSRF, validation and stale-write protection.');
} finally {
  await browser?.close();
  preview.kill('SIGTERM');
}
